const express = require('express')
const multer = require('multer')
const bhashini = require('../cataloger/providers/bhashini')
const googleRest = require('../cataloger/providers/googleRest')
const browserFallback = require('../cataloger/providers/browserFallback')
const { generateCatalogCopy } = require('../cataloger/describe')

const router = express.Router()

// Stateless, in-memory only. No persistence, no credentials in source.
const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: 8 * 1024 * 1024 },
  fileFilter: (req, file, cb) => {
    const ok = /^(audio\/|video\/webm)/.test(file.mimetype) || /\.(webm|ogg|opus|wav|m4a|mp3|mp4)$/i.test(file.originalname || '')
    cb(null, Boolean(ok))
  }
})

const PROVIDERS = [bhashini, googleRest]
const AUDIO_MIMES = new Set(['audio/webm', 'audio/ogg', 'audio/wav', 'audio/x-wav', 'audio/mpeg', 'audio/mp4', 'video/webm'])

function safeCapability(provider) {
  try { return provider.getCapability() } catch (err) {
    return { provider: provider.NAME, kind: provider.KIND, available: false, configured: false, reason: err.message }
  }
}

router.get('/capabilities', (req, res) => {
  const providers = [...PROVIDERS, browserFallback].map(safeCapability)
  res.json({
    providers,
    backendProviderConfigured: providers.some((p) => p.kind !== 'browser' && (p.available || p.configured)),
    transcriptNote: 'Backend ASR requires a configured provider. Browser speech recognition is a fallback and may use browser-managed remote processing (it is not offline).'
  })
})

router.post('/transcribe', upload.single('audio'), async (req, res) => {
  const language = String(req.body.language || req.body.lang || 'hi')
  const file = req.file
  if (!file || !file.buffer?.length) {
    return res.status(400).json({ error: 'Audio file is required (field "audio").' })
  }
  const mimetype = file.mimetype && AUDIO_MIMES.has(file.mimetype) ? file.mimetype : 'audio/webm'
  for (const provider of PROVIDERS) {
    const cap = safeCapability(provider)
    if (!cap.available) continue
    try {
      const result = await provider.transcribe({ buffer: file.buffer, mimetype, language })
      if (result && result.text) {
        return res.json({
          transcript: result.text,
          language: result.language || language,
          provider: provider.NAME,
          capability: cap,
          fallback: false,
          warning: null
        })
      }
    } catch (err) {
      // Honest failure: never claim provider output we did not receive.
      return res.status(502).json({
        error: `Provider ${provider.NAME} failed: ${err.message}`,
        provider: provider.NAME,
        fallback: 'browser',
        warning: 'Backend transcription failed. Use browser speech recognition as fallback where supported.'
      })
    }
  }
  return res.status(503).json({
    error: 'Regional-language AI provider not configured.',
    provider: null,
    fallback: 'browser',
    warning: 'No backend ASR provider is configured (set Bhashini/Google environment variables). Use the browser speech-recognition fallback where the browser supports this language; browser recognition is not offline.'
  })
})

router.post('/describe', (req, res) => {
  const body = req.body || {}
  const hasAny = ['transcript', 'englishText', 'hindiText', 'productName', 'category', 'material', 'technique', 'origin', 'details']
    .some((key) => typeof body[key] === 'string' && body[key].trim())
  if (!hasAny) {
    return res.status(400).json({ error: 'Provide at least one of: transcript, productName, category, material, technique, details.' })
  }
  try {
    const result = generateCatalogCopy(body)
    res.json({ ...result, dataSource: 'deterministic-templates+glossary', disclaimer: 'Generated by deterministic templates, not an LLM. Review before publishing.' })
  } catch (err) {
    res.status(500).json({ error: `Description generation failed: ${err.message}` })
  }
})

module.exports = router
